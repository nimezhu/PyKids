# Lesson 2: Variables - boxes with names
#
# A VARIABLE is a named box that holds a value.
# The = sign means "put this value into the box".

name = "Will"
age = 10
favourite_colour = "blue"

print(name)
print(age)

# You can print several things at once - separate them with commas:
print(name, "is", age, "years old.")
print(name, "likes", favourite_colour)

# A variable can change. The box gets a new value:
age = age + 1
print("Next year", name, "will be", age)

