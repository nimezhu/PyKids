# Lesson 3: Talking to your program
#
# input() asks a question and waits for an answer.
# Click on the OUTPUT window, type your answer, and press Enter.

name = input("What is your name? ")
print("Nice to meet you,", name + "!")

food = input("What is your favourite food? ")
print("Yum!", food, "sounds delicious.")

# The + sign glues text together:
print("Hello " + name + ", I also like " + food + ".")

